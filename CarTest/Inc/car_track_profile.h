#ifndef CARTEST_CAR_TRACK_PROFILE_H
#define CARTEST_CAR_TRACK_PROFILE_H

#ifndef CARTEST_TRACK_PROFILE
#define CARTEST_TRACK_PROFILE 0
#endif
#ifndef CARTEST_ACKERMANN_FASTEST_STRAIGHT_MILLIRPS
#define CARTEST_ACKERMANN_FASTEST_STRAIGHT_MILLIRPS 4800u
#endif
#ifndef CARTEST_ACKERMANN_SLOWEST_REQUEST_MILLIRPS
#define CARTEST_ACKERMANN_SLOWEST_REQUEST_MILLIRPS 4000u
#endif

#if CARTEST_TRACK_PROFILE < 0 || CARTEST_TRACK_PROFILE > 3
#error "CARTEST_TRACK_PROFILE must be 0 (legacy) or 1, 2, 3 (paired profiles)."
#endif

#if (CARTEST_TRACK_PROFILE == 1 || CARTEST_TRACK_PROFILE == 3)
#if CARTEST_ACKERMANN_FASTEST_STRAIGHT_MILLIRPS != 5600u || \
    CARTEST_ACKERMANN_SLOWEST_REQUEST_MILLIRPS != 4400u
#error "Track profiles A and C require 5600/4400 milli-RPS targets."
#endif
#else
#if CARTEST_ACKERMANN_FASTEST_STRAIGHT_MILLIRPS != 4800u || \
    CARTEST_ACKERMANN_SLOWEST_REQUEST_MILLIRPS != 4000u
#error "Legacy and track profile B require 4800/4000 milli-RPS targets."
#endif
#endif

#ifndef CARTEST_SPEED_PERCENT
#define CARTEST_SPEED_PERCENT 100u
#endif
#if CARTEST_SPEED_PERCENT != 100u && CARTEST_SPEED_PERCENT != 120u && \
    CARTEST_SPEED_PERCENT != 130u && CARTEST_SPEED_PERCENT != 140u
#error "Unsupported wheel-target percentage."
#endif
#if CARTEST_SPEED_PERCENT != 100u && CARTEST_TRACK_PROFILE == 0
#error "Speed variants require the original A/B/C pairing profile."
#endif
#define CARTEST_EFFECTIVE_FASTEST_MILLIRPS \
    ((CARTEST_ACKERMANN_FASTEST_STRAIGHT_MILLIRPS * CARTEST_SPEED_PERCENT) / 100u)
#define CARTEST_EFFECTIVE_SLOWEST_MILLIRPS \
    ((CARTEST_ACKERMANN_SLOWEST_REQUEST_MILLIRPS * CARTEST_SPEED_PERCENT) / 100u)

enum {
    CAR_TRACK_PROFILE_LEGACY = 0u,
    CAR_TRACK_PROFILE_DEBUG_FAST_NO_RING = 1u,
    CAR_TRACK_PROFILE_DEBUG_RING_BASE = 2u,
    CAR_TRACK_PROFILE_DEBUG_RING_FAST = 3u
};

#endif /* CARTEST_CAR_TRACK_PROFILE_H */
