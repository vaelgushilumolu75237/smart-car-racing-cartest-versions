"""Compare the OpenMV Viper gray kernels with the CPython reference output.

The board manifest is generated by the RAM-only runtime probe.  CPython's
decorator shim cannot certify Viper compilation, so the board test requires
``backend=micropython-viper`` and the exact local source SHA before comparing
the complete reusable planes and mask diagnostics.

Run host fixture/legacy checks with:
    python -B -m unittest tests.test_fast_kernels_equivalence -v

After the board manifest exists, require actual board evidence with:
    $env:V7_REQUIRE_BOARD_KERNEL_EQUIVALENCE='1'
    python -B -m unittest tests.test_fast_kernels_equivalence -v
"""

import hashlib
import json
import os
from pathlib import Path
import sys
import unittest


TEST_ROOT = Path(__file__).resolve().parents[1]
OPENMV_DIR = TEST_ROOT / "openmv"
RESULT_PATH = (TEST_ROOT / "test-data" /
               "v7-kernel-equivalence-2026-10-05" /
               "board-results.json")
if str(OPENMV_DIR) not in sys.path:
    sys.path.insert(0, str(OPENMV_DIR))

import config
import fast_gray
import grayscale_adapter


WIDTH = 80
HEIGHT = 60
INPUT_WIDTH = 160
INPUT_HEIGHT = 120
INPUT_BYTES = INPUT_WIDTH * INPUT_HEIGHT
PIXELS = WIDTH * HEIGHT
PLANE_NAMES = ("luma", "road_mask", "edge_mask", "known_region")
FIXTURE_NAMES = (
    "bluegray_narrowblack",
    "shadow_seams",
    "unknown_bottom",
    "all_byte_values",
)
DIAGNOSTIC_NAMES = (
    "sampling_source", "valid", "complete", "reason",
    "trusted_block_count", "thresholds", "raw_thresholds", "contrasts",
    "classes", "class_means", "trusted", "reasons", "road_pixels",
    "edge_pixels", "contrast_min", "contrast_max", "threshold_min",
    "threshold_max", "row_counts_sha256", "road_row_counts_sha256",
)
FLOAT_DIAGNOSTIC_ATOL = 1e-4


def _grid_to_raw(grid):
    if len(grid) != PIXELS:
        raise ValueError("fixture grid must be exactly 80x60")
    raw = bytearray(INPUT_BYTES)
    for y in range(HEIGHT):
        input_row = y * 2 * INPUT_WIDTH
        grid_row = y * WIDTH
        for x in range(WIDTH):
            value = grid[grid_row + x]
            source_index = input_row + x * 2
            raw[source_index] = value
            raw[source_index + 1] = value
            raw[source_index + INPUT_WIDTH] = value
            raw[source_index + INPUT_WIDTH + 1] = value
    return raw


def _lane_grid(dark, bright, left, right, floor=20):
    grid = bytearray(PIXELS)
    for y in range(HEIGHT):
        row = y * WIDTH
        lane = y >= floor
        for x in range(WIDTH):
            grid[row + x] = bright if lane and left <= x <= right else dark
    return grid


def fixture_inputs():
    """Yield deterministic raw source buffers, matching the board formulas."""
    grid = _lane_grid(31, 224, 22, 57)
    raw = _grid_to_raw(grid)
    # A single source pixel in one 2x2 sample must survive min-pooling.
    raw[80 * INPUT_WIDTH + 80] = 0
    yield "bluegray_narrowblack", raw

    grid = _lane_grid(34, 226, 18, 61)
    for y in range(35, 42):
        row = y * WIDTH
        for x in range(22, 59):
            grid[row + x] = 148
    # Horizontal seams span the source image; the vertical seam is inside
    # the lane.  These assignments follow the shadow patch intentionally.
    for y in (30, 44):
        row = y * WIDTH
        for x in range(WIDTH):
            grid[row + x] = 92
    for y in range(20, HEIGHT):
        row = y * WIDTH
        grid[row + 33] = 92
        grid[row + 34] = 92
    yield "shadow_seams", _grid_to_raw(grid)

    grid = _lane_grid(30, 220, 20, 60)
    for y in range(46, HEIGHT):
        row = y * WIDTH
        for x in range(WIDTH):
            grid[row + x] = 95
    yield "unknown_bottom", _grid_to_raw(grid)

    grid = bytearray(PIXELS)
    starts = (20, 32, 46)
    ends = (32, 46, 60)
    for block in range(3):
        start_y = starts[block]
        end_y = ends[block]
        for y in range(start_y, end_y):
            row = y * WIDTH
            base = (y - start_y) * WIDTH
            for x in range(WIDTH):
                grid[row + x] = (base + x) & 255
    yield "all_byte_values", _grid_to_raw(grid)


class _Frame:
    def __init__(self, raw):
        self._raw = raw

    def width(self):
        return INPUT_WIDTH

    def height(self):
        return INPUT_HEIGHT

    def format(self):
        return "grayscale"

    def bytearray(self):
        return self._raw

    def get_pixel(self, _coordinates):
        raise AssertionError("buffer-backed fixtures must use the raw path")


def _sha(data):
    return hashlib.sha256(bytes(data)).hexdigest().upper()


def _plain(value):
    if isinstance(value, tuple):
        return [_plain(item) for item in value]
    if isinstance(value, list):
        return [_plain(item) for item in value]
    return value


def _host_record(builder, name, raw):
    frame = _Frame(raw)
    result = builder.build(frame)
    if result.get("sampling_source") != "buffer":
        raise AssertionError(name + " did not use its packed byte buffer")
    planes = {plane: _sha(result[plane]) for plane in PLANE_NAMES}
    diagnostics = result["diagnostics"]
    record = {
        "name": name,
        "input_sha256": _sha(raw),
        "plane_lengths": {plane: len(result[plane]) for plane in PLANE_NAMES},
        "plane_sha256": planes,
        "diagnostics": {
            "sampling_source": result.get("sampling_source"),
            "valid": result.get("valid"),
            "complete": result.get("complete"),
            "reason": result.get("reason"),
            "trusted_block_count": result.get("trusted_block_count"),
            "thresholds": _plain(result.get("thresholds")),
            "raw_thresholds": _plain(result.get("raw_thresholds")),
            "contrasts": _plain(result.get("contrasts")),
            "classes": _plain(result.get("classes")),
            # Class means are retained on the builder for detailed host/board
            # comparison but are intentionally not part of the lean frame dict.
            "class_means": _plain(builder.class_means),
            "trusted": _plain(result.get("trusted")),
            "reasons": _plain(result.get("reasons")),
            "road_pixels": result.get("road_pixels"),
            "edge_pixels": result.get("edge_pixels"),
            "contrast_min": result.get("contrast_min"),
            "contrast_max": result.get("contrast_max"),
            "threshold_min": result.get("threshold_min"),
            "threshold_max": result.get("threshold_max"),
            "row_counts_sha256": _sha(result.get("row_counts")),
            "road_row_counts_sha256": _sha(result.get("road_row_counts")),
        },
    }

    old_road, old_edge, old_known, old_details = grayscale_adapter.build_masks(
        frame, config)
    if bytes(result["road_mask"]) != bytes(old_road):
        raise AssertionError(name + " road_mask differs from old adapter")
    if bytes(result["edge_mask"]) != bytes(old_edge):
        raise AssertionError(name + " edge_mask differs from old adapter")
    if bytes(result["known_region"]) != bytes(old_known):
        raise AssertionError(name + " known_region differs from old adapter")
    if bytes(result["luma"]) != bytes(old_details["luma"]):
        raise AssertionError(name + " luma differs from old adapter")
    return record


def host_reference_manifest():
    """Build an explicitly host-only reference manifest for the fixed cases."""
    builder = fast_gray.FastGrayMasks(config)
    fixtures = [_host_record(builder, name, raw)
                for name, raw in fixture_inputs()]
    return {
        "source_sha256": _sha((OPENMV_DIR / "fast_gray.py").read_bytes()),
        "runtime_api_version": fast_gray.RUNTIME_API_VERSION,
        "backend": fast_gray.COMPILER_BACKEND,
        "width": WIDTH,
        "height": HEIGHT,
        "floor": config.SURFACE_ROI_FLOOR_Y,
        "fixtures": fixtures,
        "evidence_scope": "CPython host reference only; Viper not compiled",
    }


def _assert_float_value(testcase, actual, expected, label):
    if actual is None or expected is None:
        testcase.assertIs(actual, expected, label)
        return
    testcase.assertTrue(
        abs(float(actual) - float(expected)) <= FLOAT_DIAGNOSTIC_ATOL,
        "%s differs: board=%r host=%r" % (label, actual, expected))


class FastKernelBoardEquivalenceTests(unittest.TestCase):
    def test_host_fixtures_match_legacy_adapter(self):
        builder = fast_gray.FastGrayMasks(config)
        records = []
        for name, raw in fixture_inputs():
            record = _host_record(builder, name, raw)
            self.assertEqual(record["plane_lengths"], {
                "luma": PIXELS,
                "road_mask": PIXELS,
                "edge_mask": PIXELS,
                "known_region": PIXELS,
            })
            records.append(record)
        self.assertEqual([record["name"] for record in records],
                         list(FIXTURE_NAMES))
        values = []
        for _name, raw in fixture_inputs():
            grid_luma = fast_gray.FastGrayMasks(config).build(_Frame(raw))["luma"]
            values.extend(grid_luma[y * WIDTH + x]
                          for y in range(20, HEIGHT)
                          for x in range(WIDTH))
        self.assertTrue(set(range(256)).issubset(set(values)))

    def test_board_viper_outputs_match_host(self):
        if not RESULT_PATH.is_file():
            if os.environ.get("V7_REQUIRE_BOARD_KERNEL_EQUIVALENCE") == "1":
                self.fail("required board result manifest is missing: " +
                          str(RESULT_PATH))
            self.skipTest("real-board Viper output manifest has not been produced")

        board = json.loads(RESULT_PATH.read_text(encoding="utf-8"))
        host = host_reference_manifest()
        source_hash = _sha((OPENMV_DIR / "fast_gray.py").read_bytes())
        self.assertEqual(board.get("source_sha256"), source_hash,
                         "board must execute the current fast_gray.py bytes")
        self.assertEqual(board.get("runtime_api_version"),
                         fast_gray.RUNTIME_API_VERSION)
        self.assertEqual(board.get("backend"), "micropython-viper",
                         "a CPython shim is not Viper kernel evidence")
        self.assertEqual(board.get("width"), WIDTH)
        self.assertEqual(board.get("height"), HEIGHT)
        self.assertEqual(board.get("floor"), config.SURFACE_ROI_FLOOR_Y)

        fixtures = board.get("fixtures")
        self.assertIsInstance(fixtures, list)
        self.assertEqual([fixture.get("name") for fixture in fixtures],
                         list(FIXTURE_NAMES))
        host_records = host["fixtures"]
        for expected, observed in zip(host_records, fixtures):
            name = expected["name"]
            with self.subTest(fixture=name):
                self.assertEqual(observed.get("input_sha256"),
                                 expected["input_sha256"])
                self.assertEqual(observed.get("plane_sha256"),
                                 expected["plane_sha256"])
                self.assertEqual(observed.get("plane_lengths"),
                                 expected["plane_lengths"])
                diagnostics = observed.get("diagnostics")
                self.assertIsInstance(diagnostics, dict)
                for key in DIAGNOSTIC_NAMES:
                    self.assertIn(key, diagnostics)
                    board_value = diagnostics[key]
                    host_value = expected["diagnostics"][key]
                    if key in ("contrasts", "class_means", "contrast_min",
                               "contrast_max"):
                        board_values = _plain(board_value)
                        host_values = _plain(host_value)
                        if isinstance(host_values, list):
                            self.assertEqual(len(board_values),
                                             len(host_values), key)
                            for index, host_item in enumerate(host_values):
                                if isinstance(host_item, list):
                                    self.assertEqual(len(board_values[index]),
                                                     len(host_item), key)
                                    for subindex, subitem in enumerate(host_item):
                                        _assert_float_value(
                                            self, board_values[index][subindex],
                                            subitem,
                                            "%s[%d][%d]" %
                                            (key, index, subindex))
                                else:
                                    _assert_float_value(
                                        self, board_values[index], host_item,
                                        "%s[%d]" % (key, index))
                        else:
                            _assert_float_value(self, board_values, host_values,
                                                key)
                    else:
                        self.assertEqual(_plain(board_value), host_value, key)


if __name__ == "__main__":
    unittest.main(verbosity=2)
